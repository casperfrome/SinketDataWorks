CREATE DATABASE IF NOT EXISTS studio_demo CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE studio_demo;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY, name VARCHAR(80) NOT NULL, city VARCHAR(80), created_at DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT PRIMARY KEY, name VARCHAR(120) NOT NULL, price DECIMAL(18,2) NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT PRIMARY KEY, user_id BIGINT NOT NULL, total_amount DECIMAL(18,2) NOT NULL,
 status VARCHAR(20) NOT NULL, ordered_at DATETIME NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT PRIMARY KEY, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 quantity INT NOT NULL, unit_price DECIMAL(18,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(product_id) REFERENCES products(id)
);
